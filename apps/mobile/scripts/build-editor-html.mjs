#!/usr/bin/env node
// Build the page the file editor's WebView loads: CodeMirror 6 and the page's
// bridge (scripts/editor-page/page.js) bundled by esbuild into one inline
// script (no network). Runs after npm install; the output is generated, not
// committed.
//
//   node scripts/build-editor-html.mjs

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

let build;
try {
  ({ build } = await import('esbuild'));
} catch {
  console.error('editor page: esbuild is not installed. Install the dev dependencies (npm install) and run npm run build-editor.');
  process.exit(1);
}

const result = await build({
  entryPoints: [join(root, 'scripts', 'editor-page', 'page.js')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  write: false,
  logLevel: 'error',
});

// The script goes inside <script>: a "</script" in a string or a regular
// expression would end it. "<\/" means the same in both.
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>
html, body { margin: 0; height: 100%; background: #111118; overscroll-behavior: none; -webkit-text-size-adjust: 100%; }
#editor { position: absolute; inset: 0; }
</style>
</head>
<body>
<div id="editor"></div>
<script>${js}</script>
</body>
</html>`;

const outFile = join(root, 'src', 'editor', 'editor-html.generated.ts');
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `// Generated by scripts/build-editor-html.mjs from scripts/editor-page/page.js and CodeMirror. Do not edit.\nexport const EDITOR_HTML = ${JSON.stringify(html)};\n`);
console.log(`editor page → src/editor/editor-html.generated.ts (${Math.round(html.length / 1024)} KB)`);
