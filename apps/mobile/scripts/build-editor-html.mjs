#!/usr/bin/env node
// Build the page the file editor's WebView loads: CodeMirror 6 and the page's
// bridge (scripts/editor-page/page.js) bundled by esbuild into one inline
// script (no network). Then the Lezer grammars the page does not carry
// (scripts/editor-page/grammars.js), each a script the app puts in the page
// when a file of it is shown: they use the page's CodeMirror
// (window.__sbEditorModules), and the build fails if one would carry its own.
// Runs after npm install; the output is generated, not committed.
//
//   node scripts/build-editor-html.mjs

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { GRAMMARS, SHARED_MODULE_NAMES, grammarSource } = await import('./editor-page/grammars.js');

let build;
try {
  ({ build } = await import('esbuild'));
} catch {
  console.error('editor page: esbuild is not installed. Install the dev dependencies (npm install) and run npm run build-editor.');
  process.exit(1);
}

const result = await build({
  entryPoints: [join(root, 'scripts', 'editor-page', 'page.js')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  write: false,
  logLevel: 'error',
});

// The script goes inside <script>: a "</script" in a string or a regular
// expression would end it. "<\/" means the same in both.
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>
html, body { margin: 0; height: 100%; background: #111118; overscroll-behavior: none; -webkit-text-size-adjust: 100%; }
#editor { position: absolute; inset: 0; }
</style>
</head>
<body>
<div id="editor"></div>
<script>${js}</script>
</body>
</html>`;

const outFile = join(root, 'src', 'editor', 'editor-html.generated.ts');
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, `// Generated by scripts/build-editor-html.mjs from scripts/editor-page/page.js and CodeMirror. Do not edit.\nexport const EDITOR_HTML = ${JSON.stringify(html)};\n`);
console.log(`editor page → src/editor/editor-html.generated.ts (${Math.round(html.length / 1024)} KB)`);

// ── The grammars ─────────────────────────────────────────────────────

const escape = (s) => s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
const sharedModules = {
  name: 'page-modules',
  setup(b) {
    b.onResolve({ filter: new RegExp(`^(${SHARED_MODULE_NAMES.map(escape).join('|')})$`) }, (args) => ({ path: args.path, namespace: 'page' }));
    b.onLoad({ filter: /.*/, namespace: 'page' }, (args) => ({
      contents: `const m = window.__sbEditorModules && window.__sbEditorModules[${JSON.stringify(args.path)}];
if (!m) throw new Error('The editor page does not give ${args.path} to its grammars');
module.exports = m;`,
      loader: 'js',
    }));
  },
};

const scripts = {};
let total = 0;
for (const key of Object.keys(GRAMMARS)) {
  const grammar = await build({
    stdin: { contents: grammarSource(key), resolveDir: root, sourcefile: `lang-${key}.js`, loader: 'js' },
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    write: false,
    metafile: true,
    plugins: [sharedModules],
    logLevel: 'error',
  });
  const stray = Object.keys(grammar.metafile.inputs).filter((file) => SHARED_MODULE_NAMES.some((name) => file.includes(`node_modules/${name}/`)));
  if (stray.length) {
    console.error(`editor page: the ${key} grammar would carry its own copy of the page's modules:\n  ${stray.join('\n  ')}`);
    process.exit(1);
  }
  scripts[`lang-${key}`] = grammar.outputFiles[0].text;
  total += grammar.outputFiles[0].text.length;
}

// U+2028 and U+2029 escaped, as bridge.ts call() does: older engines end a string at them.
const json = JSON.stringify(scripts).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
const languagesFile = join(root, 'src', 'editor', 'editor-languages.generated.ts');
writeFileSync(languagesFile, `// Generated by scripts/build-editor-html.mjs from scripts/editor-page/grammars.js. Do not edit.
// The script of each grammar the editor page asks for ({ type: 'needLanguage', addon }), by its add-on.
export const EDITOR_LANGUAGES: Record<string, string> = ${json};\n`);
console.log(`editor grammars → src/editor/editor-languages.generated.ts (${Object.keys(scripts).length}, ${Math.round(total / 1024)} KB)`);
