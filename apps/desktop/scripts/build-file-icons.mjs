#!/usr/bin/env node
// Write public/file-icon-theme.js, the file icon theme's data for the
// window's Files and Git tabs, from the material-icon-theme package in
// node_modules (its icons are loaded from there as they are). Run it again
// after updating that package:
//
//   node scripts/build-file-icons.mjs

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkgDir = join(root, 'node_modules', 'material-icon-theme');
const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
const manifest = JSON.parse(readFileSync(join(pkgDir, 'dist', 'material-icons.json'), 'utf8'));
const require = createRequire(import.meta.url);
const { folderBaseName, fileIconName } = require(join(root, 'public', 'file-icons.js'));

const folderNames = {};
for (const [name, icon] of Object.entries(manifest.folderNames)) {
  const base = folderBaseName(name);
  if (folderNames[base] && folderNames[base] !== icon) throw new Error(`Folder ${name}: ${icon} or ${folderNames[base]}?`);
  folderNames[base] = icon;
}
// VS Code matches names and extensions case-insensitively, so the theme's
// keys are kept in lower case (it lists a few, like APKBUILD, in upper case).
const lowerKeys = (map) => {
  const out = {};
  for (const [key, icon] of Object.entries(map)) {
    const lower = key.toLowerCase();
    if (!(lower in out)) out[lower] = icon;
  }
  return out;
};
const sorted = (map) => Object.fromEntries(Object.entries(map).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
const theme = {
  version: pkg.version,
  file: manifest.file,
  folder: manifest.folder,
  folderOpen: manifest.folderExpanded,
  fileNames: sorted(lowerKeys(manifest.fileNames)),
  fileExtensions: sorted(lowerKeys(manifest.fileExtensions)),
  folderNames: sorted(folderNames),
};

// The lookup must give what VS Code gives for every name the theme lists.
for (const [name, icon] of Object.entries(theme.fileNames)) {
  if (fileIconName(theme, name) !== icon) throw new Error(`File ${name}: ${fileIconName(theme, name)}, not ${icon}`);
}
for (const [name, icon] of Object.entries(manifest.folderNames)) {
  if (fileIconName(theme, name, { dir: true }) !== icon) throw new Error(`Folder ${name}: not ${icon}`);
  if (fileIconName(theme, name, { dir: true, open: true }) !== manifest.folderNamesExpanded[name]) throw new Error(`Open folder ${name}`);
}
// An icon is named in the theme; its SVG file can have another name (an icon
// that reuses another's drawing). Only those are listed, under `files`.
const icons = new Set([theme.file, theme.folder, theme.folderOpen, ...Object.values(theme.fileNames),
  ...Object.values(theme.fileExtensions), ...Object.values(folderNames).flatMap(i => [i, `${i}-open`])]);
const files = {};
for (const icon of icons) {
  const definition = manifest.iconDefinitions[icon];
  if (!definition) throw new Error(`No definition for icon ${icon}`);
  const file = basename(definition.iconPath, '.svg');
  if (!existsSync(join(pkgDir, 'icons', `${file}.svg`))) throw new Error(`Missing icon ${file}.svg`);
  if (file !== icon) files[icon] = file;
}
theme.files = sorted(files);

const license = readFileSync(join(pkgDir, 'LICENSE'), 'utf8').trim().split('\n').map(l => `// ${l}`.trimEnd()).join('\n');
const out = `// Generated by scripts/build-file-icons.mjs from material-icon-theme ${pkg.version}. Do not edit.
// The icons themselves are node_modules/material-icon-theme/icons/*.svg.
//
${license}

window.FILE_ICON_THEME = ${JSON.stringify(theme)};
`;
writeFileSync(join(root, 'public', 'file-icon-theme.js'), out);
console.log(`public/file-icon-theme.js: ${Object.keys(theme.fileNames).length} names, ${Object.keys(theme.fileExtensions).length} extensions, ${Object.keys(folderNames).length} folders, ${icons.size} icons`);
